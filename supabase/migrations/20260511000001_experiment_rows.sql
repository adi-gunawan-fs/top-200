create table if not exists public.experiment_rows (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  brand_name text not null default '',
  dish_id text not null default '',
  dish_name text not null default '',
  before_name text not null default '',
  after_name text not null default '',
  name_status text not null default 'NULL',
  before_description text not null default '',
  after_description text not null default '',
  description_status text not null default 'NULL',
  before_ingredient text not null default '',
  after_ingredient text not null default '',
  ingredient_status text not null default 'NULL',
  before_addons text not null default '',
  after_addons text not null default '',
  addons_status text not null default 'NULL',
  before_allergens text not null default '',
  after_allergens text not null default '',
  allergens_status text not null default 'NULL',
  before_diets text not null default '',
  after_diets text not null default '',
  diets_status text not null default 'NULL',
  created_at timestamptz not null default now()
);

create index if not exists experiment_rows_user_created_idx
  on public.experiment_rows(user_id, created_at desc);

alter table public.experiment_rows enable row level security;

do $$ begin
  if not exists (
    select 1 from pg_policies
    where tablename = 'experiment_rows'
      and policyname = 'Users can read own experiment rows'
  ) then
    create policy "Users can read own experiment rows"
      on public.experiment_rows for select
      to authenticated
      using (auth.uid() = user_id);
  end if;
end $$;

do $$ begin
  if not exists (
    select 1 from pg_policies
    where tablename = 'experiment_rows'
      and policyname = 'Users can insert own experiment rows'
  ) then
    create policy "Users can insert own experiment rows"
      on public.experiment_rows for insert
      to authenticated
      with check (auth.uid() = user_id);
  end if;
end $$;

